def test_separation_of_duties_approval(client):
    # MSG-0003 was generated by Vikas More (EXTENSION_WORKER)
    # 1. Non-officer cannot approve
    worker_headers = {"X-Actor": "Vikas More", "X-Role": "EXTENSION_WORKER"}
    r1 = client.post("/api/messages/MSG-0003/approve", headers=worker_headers, json={"note": "Approve"})
    assert r1.status_code == 403
    assert r1.json()["code"] == "FORBIDDEN"

    # 2. Officer cannot approve if they drafted it (MSG-0004 was drafted by Asha Kulkarni)
    asha_headers = {"X-Actor": "Asha Kulkarni", "X-Role": "DEPT_OFFICER"}
    r2 = client.post("/api/messages/MSG-0004/approve", headers=asha_headers, json={"note": "Self approve"})
    assert r2.status_code == 403
    assert r2.json()["code"] == "FORBIDDEN"
    assert "Separation of duties" in r2.json()["detail"]

    # 3. Independent Department Officer CAN approve
    officer_headers = {"X-Actor": "R. K. Sharma", "X-Role": "DEPT_OFFICER"}
    r3 = client.post("/api/messages/MSG-0003/approve", headers=officer_headers, json={"note": "Approved by senior officer"})
    assert r3.status_code == 200
    assert r3.json()["status"] == "APPROVED"
    assert r3.json()["approvedBy"] == "R. K. Sharma"


